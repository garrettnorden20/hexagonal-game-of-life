#!/usr/bin/env node
'use strict';
// patterns.json is the single editable preset source. Both browser artifacts
// are deterministic and committed so GitHub Pages needs no build tooling.
const fs = require('node:fs');
const path = require('node:path');
const H = require('./engine');
const patterns = JSON.parse(fs.readFileSync(path.join(__dirname, 'patterns.json'), 'utf8'));
const ids = new Set();
for (const p of patterns) {
  if (!p.id || ids.has(p.id)) throw new Error(`Missing or duplicate preset ID: ${p.id}`);
  ids.add(p.id);
  H.makeRule(p.rule);
  if (!Array.isArray(p.seed) || p.seed.some(c => !Array.isArray(c) || c.length !== 2 || !c.every(Number.isSafeInteger))) {
    throw new Error(`Invalid integer axial coordinates: ${p.id}`);
  }
  if (H.makeCells(p.seed).size !== p.seed.length) throw new Error(`Duplicate seed cells: ${p.id}`);
}
const bundle = `// Generated by build-standalone.js from patterns.json.\nwindow.HEX_PATTERNS = ${JSON.stringify(patterns)};\n`;
let html = fs.readFileSync(path.join(__dirname, 'lab.html'), 'utf8');
for (const name of ['engine.js', 'patterns.js']) {
  const source = (name === 'patterns.js' ? bundle : fs.readFileSync(path.join(__dirname, name), 'utf8')).replace(/<\/script/gi, '<\\/script');
  const re = new RegExp(`<script\\s+src=["'](?:\\./)?${name.replace('.', '\\.')}["']\\s*><\\/script>`);
  if (!re.test(html)) throw new Error(`Missing external script tag: ${name}`);
  html = html.replace(re, () => `<script>\n${source}\n</script>`);
}
for (const [name, expected] of [['patterns.js', bundle], ['hex-life-lab.html', html]]) {
  const file = path.join(__dirname, name);
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== expected) {
      throw new Error(`Stale ${name}; run node experiments/build-standalone.js`);
    }
  } else fs.writeFileSync(file, expected);
}
console.log(`${process.argv.includes('--check') ? 'Checked' : 'Built'} browser bundles; ${patterns.length} exact presets`);
